CREATE TABLE optimization_run (
  id UUID PRIMARY KEY,
  max_transporters INTEGER NOT NULL,
  total_cost NUMERIC(16,2) NOT NULL,
  selected_transporters INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE lane (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id UUID NOT NULL REFERENCES optimization_run(id) ON DELETE CASCADE,
  external_id VARCHAR(120) NOT NULL,
  origin VARCHAR(200) NOT NULL,
  destination VARCHAR(200) NOT NULL,
  UNIQUE(run_id, external_id)
);
CREATE TABLE transporter (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id UUID NOT NULL REFERENCES optimization_run(id) ON DELETE CASCADE,
  external_id VARCHAR(120) NOT NULL,
  name VARCHAR(200) NOT NULL,
  UNIQUE(run_id, external_id)
);
CREATE TABLE lane_quote (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lane_id BIGINT NOT NULL REFERENCES lane(id) ON DELETE CASCADE,
  transporter_id BIGINT NOT NULL REFERENCES transporter(id) ON DELETE CASCADE,
  amount NUMERIC(16,2) NOT NULL CHECK(amount >= 0),
  UNIQUE(lane_id, transporter_id)
);
CREATE TABLE lane_assignment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id UUID NOT NULL REFERENCES optimization_run(id) ON DELETE CASCADE,
  lane_external_id VARCHAR(120) NOT NULL,
  transporter_external_id VARCHAR(120) NOT NULL,
  quote_amount NUMERIC(16,2) NOT NULL,
  UNIQUE(run_id, lane_external_id)
);
CREATE INDEX idx_optimization_run_created_at ON optimization_run(created_at DESC);
